"""Build an 'all strings sustain' SFZ from VSCO 2 Community Edition (CC0) for learning.

Folder names in VSCO2 use different octave conventions, so every sample's pitch is
measured from the audio; per folder the octave offset is taken from the majority.
Layers: v1 = soft (vel 1-80), v2/v3 = loud (81-127). Key ranges like OpenSection's
registers: contrabass < 43 <= cello < 55 <= viola < 67 <= violin.

usage: vsco2_sfz.py <VSCO-2-CE dir> <out.sfz>
"""
import re, sys, subprocess, pathlib, collections
import numpy as np

FOLDERS = [("Solo Contrabass/SusVib", 0, 42), ("Cello Section/susvib", 43, 54),
           ("Viola Section/susvib", 55, 66), ("Violin Section/susVib", 67, 108)]
NAMES = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}


def load(p):
    r = subprocess.run(["ffmpeg", "-v", "error", "-i", str(p), "-f", "f32le", "-ac", "1", "-ar", "48000", "-"], capture_output=True, check=True).stdout
    return np.frombuffer(r, dtype=np.float32)


def detect(x):
    """pitch via the cepstrum: robust when the fundamental of low strings is weak"""
    x = x[48000:48000 * 4]
    X = np.log(np.abs(np.fft.rfft(x * np.hanning(len(x)), 1 << 18)) + 1e-9)
    c = np.fft.irfft(X)
    q = np.arange(len(c)) / 48000
    m = (q > 1 / 1200) & (q < 1 / 25)
    return 69 + 12 * np.log2((1 / q[m][np.argmax(c[m])]) / 440)


def main(root, out):
    root = pathlib.Path(root)
    lines = ["// generated by vsco2_sfz.py from VSCO 2 Community Edition (CC0) – for learning only", "<control>",
             f"default_path={root.resolve()}/Strings/", "<global>", "ampeg_attack=0.25", "ampeg_release=0.8", "amp_veltrack=0   // recorded dynamics only (soft and loud layers)", ""]
    for folder, lo, hi in FOLDERS:
        files = sorted((root / "Strings" / folder).glob("*.wav"))
        named, offs = [], []
        for f in files:
            m = re.search(r"_([A-G])(#?)(\d)_v(\d)", f.name)
            if not m: continue
            nm = 12 * (int(m.group(3)) + 1) + NAMES[m.group(1)] + (1 if m.group(2) else 0)
            layer = int(m.group(4))
            d = detect(load(f))
            offs.append(int(round((d - nm) / 12)) * 12)
            named.append((f, nm, layer))
        off = collections.Counter(offs).most_common(1)[0][0]
        print(f"{folder}: {len(named)} Samples, Oktav-Korrektur {off:+d}")
        for soft in (True, False):
            sel = sorted([(nm + off, f) for f, nm, l in named if (l == 1) == soft])
            keys = [k for k, _ in sel]
            for i, (k, f) in enumerate(sel):
                a = lo if i == 0 else max(lo, (keys[i - 1] + k) // 2 + 1)
                b = hi if i == len(sel) - 1 else min(hi, (k + keys[i + 1]) // 2)
                if a > b: continue
                lines += ["<region>", f"sample={f.relative_to(root / 'Strings')}", f"pitch_keycenter={k}",
                          f"lokey={a}", f"hikey={b}", "lovel=1" if soft else "lovel=81", "hivel=80" if soft else "hivel=127", "offset=4000", ""]
    pathlib.Path(out).write_text("\n".join(lines))
    print("geschrieben:", out)


if __name__ == "__main__":
    main(*sys.argv[1:3])
